// Prepares the Cloudflare version of Crash Out from the game's own files. Run before every
// deploy: `node cloudflare/build.mjs` (wrangler does it by itself, see wrangler.jsonc).
//   cloudflare/public/              the page, config.js and vendor/three.js: what a browser downloads
//   cloudflare/src/sim.generated.js the game's script as a module, for the rooms to run
// Cloudflare does not allow code to be built from text while it runs, so the wrapping that
// server.js does at start-up is done here, ahead of time. Both are generated: never edit them.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { simBody, SIM_ARGS } from '../room-core.mjs';

const here = path.dirname(fileURLToPath(import.meta.url)), game = path.join(here, '..'), pub = path.join(here, 'public');
fs.mkdirSync(path.join(pub, 'vendor'), { recursive: true });   // files are overwritten in place: the folder is never removed, so a running `wrangler dev` keeps serving
const same = (a, b) => fs.existsSync(b) && fs.readFileSync(a).equals(fs.readFileSync(b));
const put = (file, data) => { if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== data) fs.writeFileSync(file, data); };   // only touch what changed, so a watcher is not set off for nothing
for (const f of ['index.html', 'config.js', 'vendor/three.js']) if (!same(path.join(game, f), path.join(pub, f))) fs.copyFileSync(path.join(game, f), path.join(pub, f));
const body = simBody(fs.readFileSync(path.join(game, 'config.js'), 'utf8'), fs.readFileSync(path.join(game, 'index.html'), 'utf8'));
put(path.join(here, 'src', 'sim.generated.js'), `// GENERATED by cloudflare/build.mjs from index.html and config.js. Do not edit.\nexport function runGame(${SIM_ARGS.join(', ')}) {\n${body}\n}\n`);
console.log('cloudflare build: public/ and src/sim.generated.js written');
